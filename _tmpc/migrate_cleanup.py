def do(paper):
    fn = FILES[paper]
    p = os.path.join(BASE, fn)
    with io.open(p, encoding='utf-8') as f:
        t = f.read()
    orig = t
    rep = 0
    for pk, old, new in BLOCKS:
        if pk != paper:
            continue
        c = t.count(old)
        if c == 0:
            print('  ✗ [%s] BLOCK 未命中: %.50s' % (paper, old))
            continue
        t = t.replace(old, new)
        rep += c
    for pk, old, new in SUB:
        if pk != paper:
            continue
        c = t.count(old)
        if c == 0:
            print('  ✗ [%s] 未命中: %.40s' % (paper, old))
            continue
        t = t.replace(old, new)
        rep += c
    if t != orig:
        with io.open(p, 'w', encoding='utf-8', newline='') as f:
            f.write(t)
        with io.open(p, encoding='utf-8') as f:
            rb = f.read()
        assert rb == t, '[%s] 回读不一致！' % paper
    return rep

for pk in FILES:
    n = do(pk)
    print('✓ %s 替换 %d 处' % (pk, n))
