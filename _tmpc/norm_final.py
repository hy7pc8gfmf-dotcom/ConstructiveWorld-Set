summary = {}
for fn in P:
    path = os.path.join(BASE, fn)
    with io.open(path, encoding='utf-8') as f:
        t = f.read()
    before = dict((k, t.count(k)) for k in CHECK)
    n = 0
    for old, new in REPS:
        c = t.count(old)
        if c:
            t = t.replace(old, new); n += c
    c = len(WAVE.findall(t))
    if c:
        t = WAVE.sub(lambda m: (m.group(0)[0] if m.group(0)[0] in '；，' else '。'), t)
