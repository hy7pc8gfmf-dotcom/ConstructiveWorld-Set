# -*- coding: utf-8 -*-
"""规范性修订扫描器：按 E201/E178 分类（E 内部引用 / F 历史引用 / G 更新信息 / H 评审信息 / A·B 词类）
输出每条命中的 文件·行号·类别·上下文片段，供逐条裁决。"""
import io, os, re, sys, json

BASE = r'D:\ComplexAnalysis\ConstructiveWorld\演变\相关论文\分析论文'
PAPERS = ['论文1-构造性ML对齐统一形式化-正式版.md',
          '论文2-自由能原理与注意力Gibbs桥-正式版.md',
          '论文3-构造性柯西实数指数正性-正式版.md',
          '论文4-资源受限收敛动力学与PCT-正式版.md']

# (类别, 正则, 说明)
PATTERNS = [
 # ---- E 类：内部引用 ----
 ('E', r'E\d{3}(?:[-–]\d+)?', '经验卡号'),
 ('E', r'_dbg_[\w.]*', '调试探针名'),
 ('E', r'探针', '探针'),
 ('E', r'经验卡', '经验卡'),
 ('E', r'内部文档|内部语|内部黑话|内部标识', '内部文档/语'),
 ('E', r'席位?[A-Z0-9]*\s*(席|工单|任务书)', '席位/工单/任务书'),
 ('E', r'施工席位|施工席|开工件|完工件|交付报告|交接文档', '施工/交付内部语'),
 ('E', r'卡在册|已在册|在册|落册|登记于|入册', '登记/在册'),
 ('E', r'归并记录|归并席|并入后|棒\d|第[一二三四五六七八九十]+棒', '并棒/归并'),
 ('E', r'审计\s*卡|反查卡|对账卡', '内部卡'),
 # ---- F 类：历史引用 ----
 ('F', r'\bv\d{2,3}\b', '版本号'),
 ('F', r'20\d\d-\d\d-\d\d', '时间戳'),
 ('F', r'版本注记|版本行|版次注记|版本日期依据|版本快照', '版本注记'),
 ('F', r'此前遗漏|此前无|前一版|旧档|旧记载|旧快照|过期记载|历史快照|历史基线|历史形态', '历史对照'),
 ('F', r'（\s*旧|旧第\s*\d+\s*项|压缩前', '旧编号'),
 # ---- G 类：更新信息 ----
 ('G', r'更新[:：]|已更新|待补|待建|待整理|待排期|待收口|本轮|本轮次|其后另有|新增面|补充说明[:：]', '更新/待办语'),
 ('G', r'（\d{4}-\d{2}-\d{2}\s*(核验|实测|增补|更新)）', '括号内过程注'),
 ('G', r'〔[^〕]{0,60}〕', '方括号过程注'),
 # ---- H 类：评审信息 ----
 ('H', r'勘误|补正|评审指出|审读报告|评审意见|裁定|挂账|评审11|评审\s*\d', '评审/勘误'),
 ('H', r'回润|返修|送审面|投稿面|母版|规范版|正式版', '版本面/流程语'),
 # ---- A 类：内部黑话 ----
 ('A', r'战役|收官|落刀|落地|沉淀|卡点|护城河|公理脚印|开席|关席|收口|收束|棒\b|并棒|四关|温控|红线自审|定谳|判词|真死参|撞名|预检|钉死|钉定|守门|把手',
  '内部黑话'),
 ('A', r'诚实地|如实|照实|诚实注|诚实标注|诚实边界|诚实口径|诚实状态', '诚实系词（语境判定）'),
 # ---- B 类：按语境 ----
 ('B', r'闭环|崩溃|叙事|宣言', 'B 类（按语境）'),
 # ---- 其他非学术表述 ----
 ('O', r'本文的增量|增量价值|实质体量|分量|体量|杠杆比|杠杆数据', '工程语'),
 ('O', r'值得注意|值得注意的是|需要指出的是|必须强调|至关重要|极其|十分|非常', '程度副词/强调语'),
 ('O', r'我们\s*(认为|觉得|发现)|笔者', '第一人称'),
 ('O', r'！|!!|？？', '感叹/疑问'),
 ('O', r'一句话|三句话|换句话说|也就是说|简言之|一句话说', '口语连接'),
]

rows = []
for fn in PAPERS:
    p = os.path.join(BASE, fn)
    lines = io.open(p, encoding='utf-8').read().split('\n')
    for i, l in enumerate(lines, 1):
        for cat, pat, note in PATTERNS:
            for m in re.finditer(pat, l):
                s = max(0, m.start() - 55); e = min(len(l), m.end() + 55)
                rows.append({'file': fn[:4], 'line': i, 'cat': cat, 'note': note,
                             'hit': m.group(0), 'ctx': l[s:e]})

# 汇总
from collections import Counter
print('=' * 112)
print('规范性问题扫描汇总（按类别 × 文件）')
print('=' * 112)
c = Counter((r['file'], r['cat'], r['note']) for r in rows)
for (f, cat, note), n in sorted(c.items(), key=lambda x: (x[0][0], x[0][1], -x[1])):
    print('  %-5s [%s] %-18s %4d' % (f, cat, note, n))
print()
c2 = Counter(r['file'] for r in rows)
print('合计：', dict(c2), ' 总命中', len(rows))
print()
print('=' * 112)
print('按词条频次（跨篇）')
print('=' * 112)
c3 = Counter(r['hit'] for r in rows)
for w, n in c3.most_common(70):
    print('  %-30s %d' % (w, n))

json.dump(rows, io.open(r'D:\ComplexAnalysis\ConstructiveWorld-Main\_tmpc\style_scan.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
