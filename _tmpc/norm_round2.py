# 过程日期剥离（正则）
DATEPAT = re.compile(r'[；，]?\s*20\d\d-\d\d-\d\d(?:\s*/\s*\d{2})?\s*(?:grep\s*)?(?:核验|核实|实测|复核|增补|检查|测试)')

total = 0
for fn in P:
    path = os.path.join(BASE, fn)
    t = io.open(path, encoding='utf-8').read()
    n0 = 0
    for old, new, exp in REPS:
        c = t.count(old)
        if c == 0:
            continue
        if exp is not None and c != exp:
            print('  ⚠ [%s] 期望 %d 实测 %d：%s' % (fn[:4], exp, c, old[:46]))
            continue
        t = t.replace(old, new); n0 += c
    # 日期剥离
    c = len(DATEPAT.findall(t))
    t = DATEPAT.sub('', t); n0 += c
    # 清理因剥离产生的空括号
    t = t.replace('（）', '').replace('；）', '）').replace('，）', '）')
    io.open(path, 'w', encoding='utf-8', newline='').write(t)
    print('✓ %-5s 第 2 轮替换 %d 处' % (fn[:4], n0))
    total += n0
print('\n第 2 轮合计 %d 处' % total)
